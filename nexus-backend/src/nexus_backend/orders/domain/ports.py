from typing import Protocol
from uuid import UUID

from nexus_backend.orders.domain.entities import Order


class OrderRepository(Protocol):
    async def get_by_user_id(self, user_id: UUID) -> list[Order]: ...
    async def get_by_id(self, order_id: UUID) -> Order | None: ...
    async def get_by_idempotency_key(self, idempotency_key: str) -> Order | None: ...
    async def create(self, order: Order) -> Order: ...

class PaymentMethodRepository(Protocol):
    async def get_by_user_id(self, user_id: UUID) -> list["PaymentMethod"]: ...
    async def create(self, payment_method: "PaymentMethod") -> "PaymentMethod": ...
