from typing import Protocol
from uuid import UUID

from nexus_backend.catalog.domain.entities import VideoGame


class VideoGameRepository(Protocol):
    async def get_by_id(self, video_game_id: UUID) -> VideoGame | None: ...
    async def create(self, video_game: VideoGame) -> VideoGame: ...
    async def list_all(self, skip: int = 0, limit: int = 100) -> list[VideoGame]: ...
    async def get_without_embedding(self, limit: int = 100) -> list[VideoGame]: ...
    async def update(self, video_game: VideoGame) -> VideoGame: ...
    async def search_by_vector(self, embedding: list[float], top_k: int = 5) -> list[VideoGame]: ...
    async def update_stock(self, video_game_id: UUID, quantity_change: int) -> bool: ...
    async def delete(self, video_game_id: UUID) -> bool: ...
